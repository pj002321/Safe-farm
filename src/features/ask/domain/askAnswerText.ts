/**
 * ---------------------------------------------
 * [Feature]: 답변 본문에서 인라인 각주 걷어내기 (순수 함수)
 *
 * [Description]
 * - LLM 이 문장마다 근거를 "[소스 · 제목]" 형태로 답변 본문에 직접 박아 넣는다
 *   (ai-service `app/knowledge/generator.py` 의 SYSTEM_PROMPT). 같은 근거가
 *   `AskAnswer.tsx` 의 "근거 N건" 접기에도 나오므로, 본문에 겹쳐 있으면 같은
 *   정보가 두 번 보인다. 화면에서는 이걸 지우고, 저장된 답변 원문은 그대로
 *   둔다(근거 추적이 필요하면 DB 값은 안 지워졌다).
 * - 스트리밍 중에는 닫는 대괄호가 아직 안 왔을 수 있다. 그 사이엔 지우지
 *   않는다 — 여는 대괄호만 보고 지우면 그 뒤에 오는 진짜 문장까지 함께 사라진다.
 *
 * [Usage]
 * ```ts
 * hideCitations("감자는 서늘한 기후를 좋아한다. [주간농사정보 · 2024 9 감자 재배]")
 * // -> "감자는 서늘한 기후를 좋아한다."
 * ```
 * ---------------------------------------------
 */

/** `[...]` 통째로, 앞에 붙은 공백까지 지운다. 줄바꿈은 건너뛰지 않는다 —
 * 문단 하나를 통째로 삼키는 사고를 막는다. */
const CITATION = /[ \t]*\[[^[\]\n]*\]/g;

export function hideCitations(text: string): string {
  return text.replace(CITATION, "");
}
