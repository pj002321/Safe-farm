/**
 * ---------------------------------------------
 * [Feature]: 밭마다 고정된 얼굴색 (순수)
 *
 * [Description]
 * - 목록에서 카드 다섯 장이 전부 같은 얼굴이면 한눈에 구분이 안 된다. 밭마다
 *   색을 하나씩 고정해 눈이 자리를 기억하게 한다.
 * - **색으로 고른 이유.** 그림(작물 아이콘)은 의미가 있는 값이라 임의로 주면
 *   배추밭에 다른 작물이 붙어 화면이 거짓말을 한다. 색은 그런 의미가 없어서
 *   임의로 줘도 틀릴 수가 없다. 그래서 아이콘은 작물에서, 구분은 여기서.
 * - **`Math.random()` 을 쓰지 않는다.** 밭 id 에서 뽑는다. 무작위면 서버와
 *   브라우저가 다른 색을 그려 하이드레이션이 어긋나고, 새로 고칠 때마다 카드
 *   얼굴이 바뀌어 "내 배추밭은 초록"이라는 기억이 성립하지 않는다.
 *   (`fieldPatches.ts` 가 같은 이유로 씨앗 기반 PRNG 를 쓴다.)
 * - 색 **값**은 여기 없다. 이 파일은 "몇 번"만 정하고, 실제 클래스 문자열은
 *   화면이 리터럴로 들고 있다 — Tailwind 는 클래스를 정적으로 읽으므로
 *   `bg-${tone}` 같은 조립은 생성되지 않고 **조용히 사라진다.**
 *
 * [Usage]
 * ```ts
 * plotToneIndex("aaaaaaaa-0000-...");  // → 0~4
 * ```
 * ---------------------------------------------
 */

/** 준비된 얼굴색 가짓수. 화면의 리터럴 배열 길이와 **반드시 같아야** 한다. */
export const PLOT_TONE_COUNT = 5;

/**
 * 밭 id → 얼굴색 번호.
 *
 * FNV-1a 32비트. 암호용이 아니라 **짧은 문자열을 고르게 흩는** 용도로 고른 것이다.
 * uuid 는 앞자리가 몰리는 경우가 있어 단순히 첫 글자를 쓰면 색이 편중된다.
 *
 * 곱셈을 `Math.imul` 로 하는 이유: 일반 `*` 는 32비트를 넘으면 배정도 실수로
 * 올라가 하위 비트가 날아간다. 그러면 같은 해시가 겹쳐 색이 뭉친다.
 */
export function plotToneIndex(plotId: string): number {
  let hash = 0x811c9dc5;

  for (let i = 0; i < plotId.length; i += 1) {
    hash ^= plotId.charCodeAt(i);
    hash = Math.imul(hash, 0x01000193);
  }

  // `>>> 0` 로 부호를 없앤다. 음수면 나머지도 음수가 되어 배열 밖을 가리킨다.
  return (hash >>> 0) % PLOT_TONE_COUNT;
}
