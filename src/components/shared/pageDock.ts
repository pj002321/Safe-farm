/**
 * ---------------------------------------------
 * [Feature]: 페이지 전용 하단 독의 공통 id
 *
 * [Description]
 * - 어떤 화면은 자기 전용 하단 독을 띄운다(등록 마법사의 단계 조작, 마이페이지의
 *   삭제 확인). 그럴 때 공용 독(`BottomTabs`)이 비켜서야 한다 — 안 그러면 좁은
 *   화면 아래에 막대가 둘 쌓인다.
 * - `(app)/layout.tsx` 가 `group-has-[#page-dock]/app:hidden` 한 줄로 그 판단을
 *   한다. **그래서 모든 페이지 독이 같은 id 를 써야 한다.**
 *   ⚠️ 독마다 다른 id 를 주고 레이아웃에 조건을 하나씩 더하면 안 된다. 조건이
 *      다른 `group-has` 두 개를 한 요소에 붙이면 **특이도가 같아** Tailwind 의
 *      정렬 순서가 승자를 정한다 — 클래스를 적은 순서가 아니다(실측 확인).
 * - 한 화면에 페이지 독은 하나뿐이다. id 는 문서에서 유일해야 하므로 이 제약은
 *   저절로 지켜진다.
 * - 지시자 없는 평범한 모듈이다. 서버 컴포넌트(레이아웃)와 클라이언트 양쪽이
 *   읽으므로 `"use client"` 파일에 두면 안 된다(`bottomTabsLayout.ts` 의 함정).
 *
 * [Usage]
 * ```tsx
 * <div id={PAGE_DOCK_ID} className="fixed inset-x-0 bottom-0 lg:hidden">…</div>
 * ```
 * ---------------------------------------------
 */

export const PAGE_DOCK_ID = "page-dock";
