#: `crop_names` 에 `:crop` 이 **토막으로** 들어 있나. 바인드 이름은 `crop` 이다.
#:
#: ⚠ 부분 일치(`like '%배%'`)로 바꾸지 말 것. 위 ★ 의 버그가 그대로 돌아온다.
CROP_IN_NAMES = "',' || crop_names || ',' like '%,' || :crop || ',%'"
