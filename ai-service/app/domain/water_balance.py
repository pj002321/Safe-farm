"""기상만으로 물 사정을 판정한다. 작물 지식은 안 본다 — 그건 task_rules 가 곱한다.

`crop_stages.water_need_mm` 을 대신하려고 만들었다. 그 칸은 원천이 없어 428행 내내
비어 있었고(수분장력 추출 0건, '관수량' 223건은 전부 시설 관수비용표 ㎥/㏊/월),
그 한 칸이 비어서 물 규칙이 `water_need_mm is not None` 에서 막혀 **할 일 카드가
영영 0건**이었다. 필요량을 억지로 지어내는 대신 층을 둘로 갈랐다.

    시기   crop_stages.irrigate_needed   "이 단계에 물이 중요한가"   ← 연 1회. 작물 지식
    사정   이 파일                        "지금·앞으로 마르나"        ← 매일. 기상

⚠ **mm 를 지어내지 않는다.** ET0 는 **잔디 기준** 증발산이다. 작물계수(Kc)가 없으니
  "몇 mm 주세요" 를 만들 수 없다. **"물이 필요한 때다" 까지만** 간다 — 작물 차이는
  숫자가 아니라 `stage_name` 으로 문장에서 보정한다.

⚠ **Open-Meteo 토양수분은 모델값이지 측정값이 아니다.** 우리 밭의 흙도, 멀칭도,
  어제 준 물도 모른다. 그래서 이 모듈은 '말라 있다' 를 단정하지 않고 **등급**만 낸다.
  문장은 "당신 밭이 말랐습니다" 가 아니라 "2주간 비가 0.1mm 입니다" 여야 한다.

DB·LLM 의존 없음 — app/service/plot_tasks.py 가 값을 모아 여기 함수로 판정만 시킨다.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Literal

# ─────────────────────────────────────────────────────────────────────
# 임계값 셋.
#
# ⚠ **절대값이다. 조사 §4-3 은 퍼센타일을 권한다.** 토양수분 0.30 이 마른 건지는
#   흙 종류마다 다르고(모래 vs 점토), 절대 기준을 박으면 어느 지역은 늘 경보이고
#   어느 지역은 영영 조용하다. 그래도 절대값으로 먼저 띄우는 까닭 —
#   **배선이 증명되기 전에 Archive API 까지 붙이면 뭐가 문제인지 못 가린다.**
#   퍼센타일로 가는 자리는 `pipeline/region/year_deviation.py` 와 같은 패턴이다.
# ─────────────────────────────────────────────────────────────────────

# 14일 Σ(강수 − ET0) 가 이보다 낮으면 '말라 왔다'.
#
# ✅ 이 값만 실측했다 — ERA5 5지점 × 2025-04~10(각 214일, 전체 1,070일):
#       대전 16% 발동 · 해남 17% · 수원 10% · 제주 5% · 평창 4%
#       전체 10% 발동 · 10퍼센타일 = −41mm
#   전국 10% 면 "가끔 뜨는 경보" 로 알맞고, −40 이 10퍼센타일과 거의 같아 나중에
#   퍼센타일로 갈아탈 때 값이 크게 안 흔들린다.
#   다만 **지역 편향이 실제로 있다** — 대전·해남 16~17% vs 평창·제주 4~5%.
#   "절대값이라 감수한다" 가 숫자로 이 정도다.
BALANCE_DRY_MM = -40.0

# ⚠ 아래 둘은 **실측이 아니다.** 상식값으로 두고 첫 운영에서 발동 빈도를 보고 고친다.
#   근거 없는 숫자를 근거 있는 것처럼 두지 않으려고 따로 표시한다.
RAIN_SOON_MM = 5.0  # 3일 예보 강수 합이 이보다 많으면 '기다리면 된다'
RAIN_HEAVY_MM = 40.0  # 7일 예보 강수 합이 이보다 많으면 '주지 마라'

# 토양수분(m³/m³) 이 이보다 낮으면 마른 쪽으로 기운 것으로 본다.
#
# ⚠ 판정을 **혼자 뒤집지 못한다.** 모델값이라 믿을 수 있는 만큼만 쓴다 —
#   수지가 이미 마른 쪽일 때 등급을 올리는 데만 거든다(아래 `give` 참고).
#   값이 없으면(None) 판정에서 빠진다. 없는 것과 0.0 은 다르다.
SOIL_DRY = 0.20

Verdict = Literal["give", "watch", "hold", "skip"]


@dataclass
class WaterBalance:
    """한 밭의 물 사정. 전부 Open-Meteo 한 번의 호출에서 나온다.

    ⚠ 어느 칸이든 None 일 수 있다 — API 가 그 변수를 안 줬거나 과거를 안 받은 호출이다.
      **없는 것과 0 은 다르다.** 0.0mm 는 "비가 안 왔다" 이고 None 은 "모른다" 다.
    """

    #: 최근 14일 Σ(강수 − ET0). 음수면 마른 쪽으로 기울었다는 뜻이다
    balance_14d_mm: float | None = None
    #: 최근 14일에 **실제로 내린 비**(mm). 판정에는 안 쓰고 **문장에만** 쓴다.
    #:
    #: ⚠ balance_14d_mm 과 다른 값이다 — 저건 증발산을 뺀 뒤라 '비가 얼마나 왔나' 가
    #:   아니다. 사람에게는 "2주 동안 비가 0.1mm" 가 통하고 "-56mm" 는 안 통한다.
    rain_past_mm: float | None = None
    #: 위 값이 며칠치인가. "14일간" 을 문장에 적으려면 기간도 알아야 한다
    rain_past_days: int | None = None
    #: 예보 3일 강수 합
    rain_3d_mm: float | None = None
    #: 예보 7일 강수 합
    rain_7d_mm: float | None = None
    #: 토양수분 9~27cm(뿌리대), m³/m³. 표층은 소나기 한 번에 튀어 안 쓴다
    soil_moisture: float | None = None


def judge_water(b: WaterBalance) -> Verdict | None:
    """물 사정 판정 넷. 근거를 못 만들면 None — 카드 자체를 만들지 않는다.

    ⚠ **순서가 규칙의 일부다.** `hold`(예보 큰 비)를 **가장 먼저** 본다.
      2주 가물었는데 내일 60mm 가 오는 날 "물 주기" 가 먼저 뜨면 **그날 조언이
      통째로 틀린다.** 풍속 단위(`wind_speed_unit`) 때 겪은 것과 같은 꼴 —
      먼저 판정한 쪽이 뒤를 묻어 버린다.

    ⚠ None 을 돌려주는 것은 실패가 아니라 **정직한 기권**이다. 근거가 없으면
      "괜찮습니다" 라고 말하지 않는다 — 그것도 하나의 주장이기 때문이다.

    # returns
    "hold"  주지 마라 — 7일 예보 강수가 많다<br>
    "give"  물 줘라 — 말라 왔고 3일 안에 비가 없다<br>
    "watch" 신경 써라 — 말라 왔지만 3일 안에 비가 온다<br>
    "skip"  그대로 — 수지가 균형이다<br>
    None    판정할 근거가 없다<br>

    # examples
        judge_water(WaterBalance(balance_14d_mm=-52.7, rain_3d_mm=0.0, rain_7d_mm=3.0))
        -> 'give'
    """
    # ① 주지 마라 — 큰 비 예보가 모든 판정에 앞선다
    if b.rain_7d_mm is not None and b.rain_7d_mm >= RAIN_HEAVY_MM:
        return "hold"

    # ② 수지를 모르면 여기서 기권한다. 토양수분만으로는 판정하지 않는다 —
    #    모델값 하나에 조언을 걸 수 없다(파일 머리 ⚠).
    if b.balance_14d_mm is None:
        return None

    젖음 = b.balance_14d_mm > BALANCE_DRY_MM
    if 젖음:
        return "skip"

    # ③ 말라 왔다. 기다리면 되는가 —
    #    ⚠ 예보를 모르면(None) '비가 없다' 로 본다. 마른 것은 이미 사실이고,
    #      예보가 없다고 조언을 접으면 정작 필요한 날에 아무 말도 못 한다.
    if b.rain_3d_mm is not None and b.rain_3d_mm >= RAIN_SOON_MM:
        return "watch"
    return "give"


def is_soil_dry(b: WaterBalance) -> bool:
    """뿌리대 토양수분이 마른 쪽인가. **판정을 뒤집지 않고 등급만 거든다.**

    조사 §4-2 의 '물 줘라' 는 *수지 크게 음수 + 토양수분 하락 + 예보 비 없음* 셋이다.
    그런데 토양수분을 `judge_water` 의 **조건으로 넣으면 안 된다** — 값이 None 인
    호출(과거를 안 받았거나 API 가 그 변수를 안 준 경우)에서 `give` 가 통째로
    사라진다. 마른 것은 수지만으로도 이미 사실이다.

    그래서 이 함수는 따로 둔다. 쓰는 쪽(task_rules)이 `give` 일 때 이것까지 참이면
    **priority 를 올리는 데만** 쓴다.

    ⚠ 모델값이다(파일 머리 ⚠). 값이 없으면 거짓 — "모른다" 를 "말랐다" 로 읽지 않는다.
    """
    return b.soil_moisture is not None and b.soil_moisture < SOIL_DRY


def 기간말(일수: int | None) -> str | None:
    """며칠을 "14일" 처럼 **숫자로** 적는다. task_rules 도 같은 말을 써서 공개한다.

    ★ 2026-09-19 — '사흘'·'이레'·'두 주' 를 걷어 냈다.

      처음엔 토박이말이 더 사람 말 같아서 썼는데, **사흘과 나흘을 헷갈리는 사람이
      많다**(사용자 지적). 날짜를 잘못 읽으면 물 주는 날이 어긋난다 — 이 문장은
      말맛을 내려고 있는 것이 아니라 언제 무엇을 할지 정하라고 있는 것이다.
      숫자는 누구나 같게 읽는다.

    ⚠ 이레를 넘으면 **주로 센다.** "14일" 보다 "2주" 가 얼마나 긴 동안인지 바로
      잡힌다. 딱 떨어지지 않는 날수(10일)는 그냥 날로 둔다 — "1주 3일" 은 읽다가
      한 번 멈추게 된다.

    ⚠ 날수를 모르면 None 이다. 부르는 쪽이 기간을 빼고 적는다 — 옛 코드는 여기서
      "None일" 을 만들어 화면까지 흘려보낼 수 있었다.
    """
    if not 일수:
        return None
    주, 나머지 = divmod(일수, 7)
    if 주 == 0 or 나머지:
        return f"{일수}일"
    return "일주일" if 주 == 1 else f"{주}주"


#: 예보(모델)와 관측(실측)이 이만큼 벌어지면 출처를 밝힌다(mm).
#:
#: "한 번 지나간 소나기" 쯤이다 — 그만큼 차이 나면 사용자도 몸으로 안다.
#: 그 아래면 같은 말을 두 번 하는 셈이라 적지 않는다.
RAIN_DISAGREE_MM = 5.0


def 관측을_밝힐까(예보: float | None, 관측: float | None) -> bool:
    """관측 강수를 문장에 덧붙일 것인가.

    ⚠ **카드(task_rules)와 리포트(report)가 같은 규칙을 써야 한다.** 한쪽만 붙이면
      같은 밭을 두고 홈 카드와 리포트가 서로 다른 근거를 댄다.

    ⚠ 예보를 모르면(None) 관측이 유일한 근거다 — 그때는 밝힌다.
    """
    if 관측 is None:
        return False
    if 예보 is None:
        return True
    return abs(관측 - 예보) >= RAIN_DISAGREE_MM


def dryness_note(b: WaterBalance) -> str | None:
    """판정의 **근거를 사실로** 적은 한 줄. 카드 문장에 그대로 넣는다.

    ★ 2026-09-19 — **사람 말로 바꿨다.**

        예전   "최근 14일 강수에서 증발산을 뺀 값이 -56mm · 앞으로 3일 예보 강수는 0mm"
        지금   "2주 동안 비가 0.1mm뿐이었어요. 앞으로 3일도 비 소식이 없어요."

      '증발산' 도 '-56mm' 도 농민이 쓰는 말이 아니다. **계산에서 빼는 것이 아니라
      문장에서만 감춘다** — 판정은 balance_14d_mm 이 그대로 한다. 근거 추적은
      `_skip` 로그와 리포트 상세가 맡는다.

    ⚠ '마릅니다'·'부족합니다' 같은 판단어를 쓰지 않는다. 사실만 적고 판단은 카드
      제목이 한다 — 토양수분·ET0 가 모델값이라 단정할 근거가 모자란다.
    ⚠ '장마' 를 쓰지 않는다. 7일 예보로 2~4주 현상을 말할 수 없다(조사 §5-3).
    """
    조각: list[str] = []
    # 앞 문장이 "비가 적었다" 고 말했는가. 뒤 문장의 조사가 여기 걸린다
    마른편 = False

    # ── 지난 비 ───────────────────────────────────────────────
    if b.rain_past_mm is not None:
        # 날수를 모르면 기간을 빼고 적는다 — 기간말 이 None 을 준다
        기간 = 기간말(b.rain_past_days)
        머리 = f"{기간} 동안 " if 기간 else ""
        마른편 = b.rain_past_mm < 1
        if 마른편:
            조각.append(f"{머리}비가 {b.rain_past_mm:.1f}mm뿐이었어요.")
        else:
            조각.append(f"{머리}내린 비가 {b.rain_past_mm:.0f}mm 예요.")
    elif b.balance_14d_mm is not None and b.balance_14d_mm < 0:
        # 강수를 따로 못 받은 호출. 수지라도 적되 **뜻을 풀어 쓴다**
        # ⚠ 음수일 때만이다. 비가 넉넉했던 밭에 이 문장을 적으면 거짓말이 된다
        마른편 = True
        조각.append("2주 동안 비보다 마른 날이 많았어요.")

    # ── 앞으로 ────────────────────────────────────────────────
    # 3일·7일은 rain_3d_mm·rain_7d_mm 이 보는 창이다. 칸 이름과 문장을 같게 둔다
    if b.rain_3d_mm is not None and b.rain_3d_mm < 1:
        # '도' 는 앞 문장이 가물었다고 말했을 때만 이어진다
        조각.append(f"앞으로 3일{'도' if 마른편 else '은'} 비 소식이 없어요.")
    elif b.rain_3d_mm is not None:
        조각.append(f"앞으로 3일 동안 {b.rain_3d_mm:.0f}mm쯤 올 것 같아요.")
    if b.rain_7d_mm is not None and b.rain_7d_mm >= RAIN_HEAVY_MM:
        # ⚠ '장마' 가 아니라 기간과 숫자로 말한다
        조각.append(f"일주일 동안은 {b.rain_7d_mm:.0f}mm 예보예요.")

    return " ".join(조각) if 조각 else None
