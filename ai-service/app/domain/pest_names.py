"""병해충 이름을 사람이 읽을 몇 개로 추린다. **DB·LLM 의존 없음.**

`pest_bulletins` 의 `pest_name` 은 같은 것을 여러 표기로 적어 둔다. 2026-09-19
실측 — 고추 한 작물의 9월 중순 자료가 이랬다.

    바이러스‧역병‧탄저병 · 바이러스병·역병·탄저병 · 역병·탄저병·바이러스
    고추 담배나방 · 담배나방, 파밤나방

그대로 카드에 실으면 같은 말이 다섯 번 나온다. 쪼개서 겹치는 것을 걷어낸다.
"""

from __future__ import annotations

import re

#: 이름을 쪼개는 글자. 자료마다 가운뎃점이 제각각이다(·, ‧, ・).
_SPLIT = re.compile(r"[,·‧・/]")

#: 카드 한 장에 적을 최대 개수. 더 많으면 읽다가 만다 —
#: 무엇을 살펴야 하는지가 아니라 "병해충이 많구나" 만 남는다.
MAX_NAMES = 3

#: 조각의 **끝 낱말**이 이보다 짧으면 버린다.
#:
#: ⚠ 가운뎃점이 **병해충을 잇기도 하고 작물을 잇기도 한다.** '무·배추 무름병' 은
#:   "무와 배추의 무름병" 인데 쪼개면 '무' 가 병해충 이름으로 남는다. 앞에 말이
#:   붙어도 마찬가지다 — '고랭지 무·배추 무름병' 은 '고랭지 무' 를 만든다(실측).
#:
#:   끝 낱말로 재면 둘 다 걸린다. 병해충 이름의 끝은 '병·나방·멸구·응애류' 처럼
#:   두 글자를 넘고, 작물 이름은 '무·파·배' 처럼 한 글자인 것들이 문제였다.
_MIN_LEN = 2


def _쓸만한가(조각: str) -> bool:
    """병해충 이름으로 볼 만한가. 끝 낱말이 한 글자면 작물 이름이 샌 것이다."""
    낱말 = 조각.split()
    return bool(낱말) and len(낱말[-1]) >= _MIN_LEN


def merge_pest_names(names: list[str] | tuple[str, ...], limit: int = MAX_NAMES) -> tuple[str, ...]:
    """
    # summary
    여러 표기를 겹치지 않는 몇 개로. 들어온 순서를 지킨다.

    ⚠ **짧은 쪽을 남긴다.** '고추 담배나방' 과 '담배나방' 이 같이 오면 '담배나방'
      하나로 둔다 — 카드 제목에 이미 작물 이름이 있어 되풀이가 된다.

    ⚠ 이름을 고쳐 쓰지 않는다. 자료에 있는 말을 그대로 옮긴다 — 병해충 이름은
      우리가 다듬을 것이 아니다.

    # params
    names: 자료에 적힌 이름들. 한 칸에 가운뎃점으로 여럿이 들어 있을 수 있다<br>
    limit: 돌려줄 최대 개수. 넘치면 앞에서 자른다<br>

    # returns
    겹치지 않는 이름 튜플. 쓸 만한 것이 없으면 빈 튜플

    # examples
        merge_pest_names(["고추 담배나방", "담배나방"])   -> ('담배나방',)
        merge_pest_names(["무·배추 무름병"])              -> ('배추 무름병',)
    """
    조각: list[str] = []
    for 이름 in names:
        for 하나 in _SPLIT.split(이름 or ""):
            하나 = 하나.strip()
            if _쓸만한가(하나) and 하나 not in 조각:
                조각.append(하나)

    남길: list[str] = []
    for 하나 in 조각:
        # 이미 넣은 것이 이걸 품고 있으면(또는 반대면) 짧은 쪽만 남긴다
        더긴 = next((x for x in 남길 if 하나 in x), None)
        if 더긴 is not None:
            남길[남길.index(더긴)] = 하나
            continue
        if any(x in 하나 for x in 남길):
            continue
        남길.append(하나)

    return tuple(남길[:limit])
