"""
---------------------------------------------
[Feature]: 증상말 → 병해충 후보 (순수 함수)

[Description]
- 농민은 "반점" "녹는다" "시든다" 로 묻고, 문서는 "노균병" "무름병" "시들음병" 으로 적는다.
  임베딩은 이 거리를 잘 못 넘는다 — 실측: "배추에 반점" 에 반점이 적힌 검은썩음병·노균병
  문서가 안 올라오고 무름병이 올라왔다(2026-09-17). 질문에 후보 병명을 덧붙여 임베딩하면
  문서 쪽 말로 검색된다.
- 진단이 아니다. **검색어를 넓히는 것**이다. 후보를 여럿 붙이고 판단은 LLM 이 자료를 보고
  한다(V1-79).
- 순수 함수라 pytest 로 바로 검증된다. 사전은 pest_bulletins 의 실제 pest_name 109종에서 골랐다.

[Usage]
```python
expand_symptoms("배추에 반점이 올라오는데")
# -> "배추에 반점이 올라오는데 노균병 검은무늬병 검은썩음병 점무늬병 탄저병 갈색무늬병"
```
---------------------------------------------
"""

# 증상말 → 문서에 실제로 있는 병해충 이름.
# 왼쪽은 농민이 쓰는 말, 오른쪽은 pest_bulletins·weekly_notes 의 말.
# ⚠ 작물을 가리지 않는다 — 작물은 retriever 의 crops 필터가 따로 좁힌다.
_SYMPTOMS: dict[tuple[str, ...], tuple[str, ...]] = {
    ("반점", "점무늬", "얼룩", "병반"): (
        "노균병", "검은무늬병", "검은썩음병", "점무늬병", "탄저병", "갈색무늬병",
    ),
    ("녹는다", "녹아", "물러", "무른다", "썩"): (
        "무름병", "역병", "잿빛곰팡이병", "균핵병",
    ),
    ("시든다", "시들", "쳐진다", "축 처"): (
        "시들음병", "반쪽시들음병", "풋마름병", "뿌리혹병", "역병",
    ),
    ("노랗", "누렇", "황화", "누레"): (
        "노균병", "바이러스", "황화잎말림바이러스", "잎마름병",
    ),
    ("말린다", "말려", "오그라", "쭈그"): (
        "바이러스", "잎말림", "총채벌레류", "진딧물류",
    ),
    ("구멍", "갉아", "먹은 자리"): (
        "나방", "벼룩잎벌레", "담배나방", "파밤나방",
    ),
    ("하얗", "흰 가루", "흰가루", "곰팡이"): (
        "흰가루병", "잿빛곰팡이병",
    ),
    ("혹", "울퉁"): (
        "뿌리혹병", "선충",
    ),
}


def symptom_candidates(question: str) -> list[str]:
    """질문에 든 증상말마다 후보 병해충을 모은다. 순서 유지, 중복 제거. 없으면 빈 리스트."""
    out: list[str] = []
    for words, pests in _SYMPTOMS.items():
        if any(w in question for w in words):
            out.extend(p for p in pests if p not in out)
    return out


def expand_symptoms(question: str) -> str:
    """검색용 문장. 원문 뒤에 후보 병명을 붙인다 — 원문은 그대로 둔다(LLM 에는 원문만 간다)."""
    cands = symptom_candidates(question)
    return f"{question} {' '.join(cands)}" if cands else question
