"""축산 얘기인가. **이 서비스가 다루지 않는 것을 걸러내는 데 쓴다.**

★ 2026-09-19 — "호우경보가 있어. 내 밭에 뭘 해주면 좋을까?" 에 **축사 얘기가
  통째로** 나왔다. 축대 보수·사료 보관·깔짚 관리·가축 비타민·송풍팬까지.
  근거로 뽑힌 다섯 중 1·2위가 `집중호우 대비 축사 관리` 였다.

  코퍼스에 축산 문서가 섞여 있어서다. 이 서비스는 텃밭·밭작물만 다루므로
  그 문서들은 답에 닿으면 안 된다.

★ 새는 곳이 검색만이 아니었다. `disaster_bulletins` 는 작물이 '더덕'·'감자' 인 행의
  본문에도 축사 대책을 같이 적어 둔다(1,881행 중 238행). 실측 133작물 × 12달 중
  **더덕 10월**이 리포트에 "축사 주변 배수로 정비" 를 실어 보내고 있었다.
  그래서 제목과 본문을 **한 표로** 본다 — 목록이 두 곳으로 갈라지면 한쪽만 고쳐
  문제가 반쯤 살아난다(`bulletin_sql` 에서 겪은 것과 같다).

⚠ **낱말만 보면 반드시 작물이 걸린다.** 한국어는 낱말이 붙어 한 덩어리가 되기
  때문이다 — 돼지**감자**, **벌**레, **오리**엔탈 나리, **닭**의장풀, 비에 **젖**지,
  차아**염소**산. 그래서 찾은 자리마다 **둘레 글자를 보고** 판단한다.
"""

from __future__ import annotations

#: 낱말 둘레로 볼 글자 수. 한 어절(2~4자)에 조사까지 들어오는 길이다.
#: 더 넓히면 옆 어절의 '아닌 신호' 에 엉뚱하게 걸리고, 좁히면 '오리엔탈' 을 놓친다.
_문맥폭 = 6

#: 축산 낱말 → **둘레에 이것이 보이면 축산이 아니다.** 빈 튜플이면 문맥을 안 본다.
#:
#: 값은 전부 실측으로 정했다(2026-09-19: 문서 제목 10,638건 · 게시물 사전대책 항목 4,132개).
#: 문맥창 덕에 '돼지'·'오리'·'닭'·'젖' 처럼 짧은 말을 쓸 수 있게 됐다 — 낱말만 보던
#: 때는 이것들을 못 넣어 '돼지 주요질병'·'폭염 오리 사전대책' 을 놓치고 있었다.
#:
#: ⚠ `사료` 를 넣지 말 것. **사료작물은 진짜 밭작물이다** —
#:   사료용 귀리·청보리·호밀·총체벼가 코퍼스에 60종 넘게 있다.
_LIVESTOCK: dict[str, tuple[str, ...]] = {
    # 일반. 이 말들은 축산 밖에서 안 쓴다
    "가축": (),
    "축산": (),
    "축사": (),
    "우사": (),
    "돈사": (),
    "사양관리": (),
    "주령": (),  # '산란계 주령'·'오리 주령' 처럼 가금 나이를 세는 말
    "비육": (),
    # 소
    "한우": (),
    "송아지": (),
    "착유": (),
    "럼피스킨": (),
    "젖": ("젖지", "젖게", "젖어", "젖는", "비에", "물에"),  # '비에 젖지 않게 보관'
    # 돼지 — '돼지열병' 도 여기서 같이 잡힌다
    "양돈": (),
    "돼지": ("돼지감자",),
    # 가금
    "양계": (),
    "육계": (),
    "산란계": (),
    "구제역": (),
    "조류인플루엔자": (),
    "닭": ("닭의장풀",),
    "오리": ("오리엔탈", "오리나무", "봉오리"),  # 오리엔탈 나리 · 꽃봉오리
    # 염소 — 소독제(차아염소산)와 갈린다
    "염소": ("차아", "염소산", "염소계"),
    # 양봉. '폭염 봉군관리'·'장마철 벌무리 관리' 가 재해 질문에 딸려 오던 것들이다.
    #
    # ⚠ **'벌' 한 글자로 묶지 말 것.** 문맥창으로도 못 건진다 — 국화 품종
    #   **'골든페스티벌'·'문페스티벌'**, 포인세티아 '피치벌룬', '간벌', 참깨 '두벌'
    #   이 걸리고, 게시물 제목에 **'총 채 벌 레 류'** 처럼 글자를 띄어 쓴 것이 있어
    #   '벌레' 라는 신호 자체가 성립하지 않는다(2026-09-19 실측 오탐 8종).
    #   벌 이름은 그 자체로 길어 문맥이 필요 없다.
    "양봉": (),
    "봉군": (),
    "벌무리": (),
    "꿀벌": (),
    "여왕벌": (),
    "수벌": (),
    "월동벌": (),
    "봄벌": (),
    "도둑벌": (),
}


def _낱말이_축산으로_쓰였나(글: str, 낱말: str, 아닌신호: tuple[str, ...]) -> bool:
    """낱말이 나온 자리마다 둘레를 보고, '아닌 신호' 가 없는 자리가 하나라도 있으면 참.

    한 글에 같은 낱말이 여러 번 나올 수 있다 — '오리엔탈 나리와 오리 사육' 이면
    뒤쪽 자리가 축산이다. 그래서 첫 자리만 보고 끝내지 않는다.
    """
    자리 = 글.find(낱말)
    while 자리 != -1:
        창 = 글[max(0, 자리 - _문맥폭) : 자리 + len(낱말) + _문맥폭]
        if not any(신호 in 창 for 신호 in 아닌신호):
            return True
        자리 = 글.find(낱말, 자리 + 1)
    return False


def is_livestock(글: str | None) -> bool:
    """
    # summary
    이 글이 축산 얘기인가. 문서 제목(검색 후보 거르기)과 게시물 본문 한 항목
    (리포트 문장 거르기)이 같이 쓴다.

    ⚠ 글이 없으면 **거짓**이다. 모르는 것을 빼 버리면 멀쩡한 작물 자료가 조용히
      사라진다 — 빼는 쪽이 틀렸을 때의 손해가 더 크다.

    # params
    글: 문서 제목 또는 본문에서 끊어 낸 한 항목<br>

    # returns
    축산 얘기면 True

    # examples
        is_livestock("2023 31 집중호우 전·후 축사 관리")  -> True
        is_livestock("2026 27 여왕벌")                    -> True
        is_livestock("복숭아씨살이좀벌 예보")              -> False
        is_livestock("비에 젖지 않게 보관한다")            -> False
    """
    본 = 글 or ""
    return any(_낱말이_축산으로_쓰였나(본, 낱말, 아닌) for 낱말, 아닌 in _LIVESTOCK.items())
