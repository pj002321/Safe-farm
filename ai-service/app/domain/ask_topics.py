def topics_in(question: str | None) -> frozenset[str]:
    """
    # summary
    이 질문이 건드리는 갈래. 밭 컨텍스트에 무엇을 덧붙일지 고르는 데 쓴다.

    ⚠ 빈 집합이 **기본값이다.** 못 알아들었으면 아무것도 덧붙이지 않는다 —
      지금까지와 같은 답이 나가고, 사용자는 잃는 것이 없다.

    # params
    question: 사용자가 친 질문. None·빈 글이면 빈 집합<br>

    # returns
    `'satellite'`·`'pest'`·`'rain'`·`'disaster'` 중 걸린 것들. 한 질문이 여럿에 걸릴 수 있다

    # examples
        topics_in("요즘 벌레가 많아요")   -> frozenset({'pest'})
        topics_in("웃거름 언제 줘요?")    -> frozenset()
    """
    글 = question or ""
    return frozenset(갈래 for 갈래, 낱말들 in _TOPIC_WORDS.items() if any(w in 글 for w in 낱말들))
