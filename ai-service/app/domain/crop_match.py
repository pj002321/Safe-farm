"""질문에서 작물 이름을 찾는다. 검색 필터가 쓴다.

왜 필요한가:
    '마늘 씨뿌림 씨앗량' 에 '마 씨앗'(0.402) 이 '마늘 씨뿌림'(0.434) 을 이긴다.
    0.03 차이라 벡터만으로는 영영 못 가른다. 작물을 먼저 좁히고 그 안에서 거리를 본다.

⚠ 한 글자 작물이 13개다 — 마·무·파·배·조·콩·팥·밀·갓·박·벼·말·피.
  훑어 찾으면 '파종'의 '파', '재배'의 '배', '조생'의 '조' 가 전부 걸린다.
  safefarm-crop-data 의 crops.py 가 같은 함정을 겪고 만든 규칙을 가져왔다.
"""

import re
from collections.abc import Iterable

# 일반 명사와 겹치는 이름. 조사·경계가 붙은 꼴로만 인정한다.
# 두 글자여도 겹치는 것이 있다 — '가지'(枝) · '근대'(近代) · '수수'(옥수수의 일부)
AMBIGUOUS = frozenset({
    "마", "무", "파", "배", "조", "밀", "말", "갓", "박", "벼", "콩", "팥", "피",
    "가지", "근대", "수수", "동부", "기장",
})

# 모호한 이름 뒤에 올 수 있는 것: 조사 · 공백 · 문장부호 · 끝.
# '무를' '무는' '(무)' '무 씨뿌림' 은 작물, '무피복' '무경운' 은 아니다
_경계 = r"(?:$|[\s,.!?~()\[\]/·]|은|는|이|가|을|를|와|과|의|도|만|에|에서|로|으로|랑|이랑)"

# ⚠ **앞도 본다.** 뒤 경계만 보면 낱말 **끝**에 걸린 한 글자가 통과한다 —
#   '너무 많이' 의 '무' 는 뒤가 공백이라 조건을 만족했고, '재배' 의 '배' 는 뒤가 문장 끝이라
#   통과했다. 실측(2026-09-17): "방울 토마토에 물을 너무 많이" → {'무'} 로 잡혀 검색이
#   무·배추 문서에 갇혔다. 토마토 자료는 후보에 들지도 못했다.
#   앞이 한글이면 낱말 한복판이라는 뜻이므로 작물이 아니다.
#   ('\x00' 은 찾은 자리를 지운 표식이라 한글이 아니고, 그래서 경계로 인정된다 — 의도한 대로다)
_앞경계 = r"(?:^|[^가-힣])"


def find_crops(question: str, known: Iterable[str]) -> set[str]:
    """
    # summary
    질문에 나온 작물 이름을 찾는다. 긴 이름을 먼저 보고 걸린 자리는 지운다 —
    '마늘' 을 찾은 자리에서 '마' 를 또 찾지 않는다.

    # params
    question: 사용자 질문<br>
    known: 아는 작물 이름 전부. crops·crop_guides·varieties 를 합친 207개쯤<br>

    # returns
    찾은 표준 이름 집합. 못 찾으면 빈 집합 — 부르는 쪽은 그때 필터 없이 전체를 검색한다.
    괄호가 든 이름('백합(나리)')은 괄호 앞부분으로도 찾는다

    # examples
        find_crops("마늘 씨뿌림 씨앗량 얼마나?", ["마", "마늘", "상추"])  -> {'마늘'}
        find_crops("파종 시기 알려줘", ["파", "상추"])                    -> set()
        find_crops("무랑 배추 심었어", ["무", "배추"])                    -> {'무', '배추'}
    """
    남은 = question
    아는이름 = {n for n in known if n}
    찾음: set[str] = set()

    # 긴 이름부터. '강낭콩' 을 찾은 자리에서 '콩' 을 또 찾지 않으려는 것이다
    for name in sorted(아는이름, key=len, reverse=True):
        # '백합(나리)' 은 '백합' 으로도 불린다. 괄호 앞을 찾을 말로 쓴다
        찾을말 = name.split("(")[0].strip() or name
        if 찾을말 not in 남은:
            continue
        if 찾을말 in AMBIGUOUS and not re.search(_앞경계 + re.escape(찾을말) + _경계, 남은):
            continue        # 앞뒤가 다 경계여야 낱말이다. 한쪽만 보면 '너무'·'재배' 가 샌다
        찾음.add(name)
        # ⚠ 괄호 앞 이름도 같이 넣는다. '콩나물용 콩' 에서 '콩(논재배)' 만 돌려주면
        #   meta['작물'] = '콩' 인 문서가 필터에서 통째로 빠진다 — 실제로 그랬다
        #   (골든셋 variety_summary 4/5 -> 3/5). 찾은 자리를 지우기 때문에
        #   그 뒤 '콩' 차례가 와도 못 찾는다
        if 찾을말 != name and 찾을말 in 아는이름:
            찾음.add(찾을말)
        # 찾은 자리를 지운다. \x00 은 어떤 작물 이름에도 없어 다음 검색을 방해하지 않는다
        남은 = 남은.replace(찾을말, "\x00" * len(찾을말))

    return 찾음
