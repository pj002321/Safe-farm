"""한국어 조사 고르기. **DB·LLM 의존 없음.**

카드와 리포트 문장은 작물·병해충 이름을 그대로 끼워 넣는다. 그러면 받침에 따라
조사가 달라지는데, 하나로 박아 두면 "바이러스이 자주 나와요" 같은 말이 나간다.
사람이 쓴 글처럼 보이지 않으면 나머지 내용도 못 믿는다.
"""

from __future__ import annotations

#: 한글 음절 영역. 이 밖(숫자·영문·기호)은 받침을 셀 수 없다.
_한글시작 = 0xAC00
_한글끝 = 0xD7A3
_종성수 = 28


def 조사(낱말: str, 받침있을때: str, 받침없을때: str) -> str:
    """
    # summary
    끝 글자의 받침을 보고 조사를 고른다.

    ⚠ 한글이 아닌 끝 글자는 **받침 없는 쪽**으로 둔다. 숫자·영문은 읽는 법이
      제각각이라(3은 '삼', 5는 '오') 규칙으로 맞힐 수 없다. 틀리더라도 한쪽으로
      일관되게 틀리는 편이 낫다 — 우리 문장에는 작물·병해충 이름만 들어온다.

    # params
    낱말: 조사를 붙일 말. 비면 받침 없는 쪽으로 본다<br>
    받침있을때: 받침이 있을 때 쓸 조사('이'·'은'·'을')<br>
    받침없을때: 받침이 없을 때 쓸 조사('가'·'는'·'를')<br>

    # returns
    둘 중 하나. 판단이 아니라 **고르기**라 None 을 돌려주지 않는다

    # examples
        조사("담배나방", "이", "가")  -> "이"
        조사("바이러스", "이", "가")  -> "가"
    """
    if not 낱말:
        return 받침없을때
    끝 = ord(낱말[-1])
    if not (_한글시작 <= 끝 <= _한글끝):
        return 받침없을때
    return 받침있을때 if (끝 - _한글시작) % _종성수 else 받침없을때
