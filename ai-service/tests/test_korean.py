"""조사 고르기. 카드·리포트 문장에 작물·병해충 이름이 그대로 끼워 들어간다.

★ 이게 없어서 "바이러스이 자주 나와요" 가 나갔다. 사람이 쓴 글처럼 보이지
  않으면 나머지 내용도 못 믿는다.
"""

from app.domain.korean import 조사


def test_받침이_있으면_앞엣것():
    assert 조사("담배나방", "이", "가") == "이"
    assert 조사("역병", "이", "가") == "이"
    assert 조사("무름병", "은", "는") == "은"


def test_받침이_없으면_뒤엣것():
    assert 조사("바이러스", "이", "가") == "가"
    assert 조사("응애류", "이", "가") == "가"
    assert 조사("고추", "은", "는") == "는"


def test_ㄹ_받침도_받침이다():
    """'을/를' 은 ㄹ 에서 헷갈리기 쉽다."""
    assert 조사("마늘", "을", "를") == "을"
    assert 조사("서리", "을", "를") == "를"


def test_한글이_아니면_받침_없는_쪽으로():
    """숫자·영문은 읽는 법이 제각각이라(3은 '삼', 5는 '오') 규칙으로 못 맞힌다.
    틀리더라도 한쪽으로 일관되게 틀리는 편이 낫다."""
    assert 조사("NDVI", "이", "가") == "가"
    assert 조사("3", "이", "가") == "가"


def test_빈_말에도_터지지_않는다():
    """이름이 비는 일은 없어야 하지만, 문장 만드는 중에 예외가 나면 카드가 통째로 빠진다."""
    assert 조사("", "이", "가") == "가"


def test_실제로_쓰는_이름들():
    """카드에 나간 적 있는 이름 그대로 — 이 줄이 화면에 나가는 말이다."""
    for 이름, 기대 in [
        ("담배나방", "담배나방이"),
        ("파밤나방", "파밤나방이"),
        ("바이러스", "바이러스가"),
        ("깨씨무늬병", "깨씨무늬병이"),
        ("벼멸구", "벼멸구가"),
        ("반쪽시들음병", "반쪽시들음병이"),
    ]:
        assert f"{이름}{조사(이름, '이', '가')}" == 기대
