def test_기호가_없어도_그대로_쓴다():
    assert _첫항목("배수로를 정비한다") == "배수로를 정비한다"


def test_빈_본문은_빈_문자열():
    assert _첫항목("") == ""
    assert _첫항목("○  ") == ""


