"""재해 대비 본문 다듬기. DB 없이 순수 변환만 본다."""

from app.service.disaster_notes import MAX_NOTES, _첫항목


def test_항목_기호로_나눠_첫_줄만_쓴다():
    """원문이 '○' 로 항목을 잇는다. 대개 첫 항목이 핵심이다."""
    본문 = "○ 배수구를 깊게 정비한다\n○ 요소 엽면시비로 회복 촉진\n○ 병해충 방제"
    assert _첫항목(본문) == "배수구를 깊게 정비한다"


def test_줄바꿈과_겹공백을_편다():
    """원문이 한글 표에서 온 글이라 줄바꿈이 문장 가운데 들어간다."""
    assert _첫항목("○ 배수로 정비 및\n  토양유실 우려지역은  짚으로 덮고") == (
        "배수로 정비 및 토양유실 우려지역은 짚으로 덮고"
    )


def test_너무_길면_자른다():
    """한 항목에 여러 문장을 잇는 일이 있다 — 프롬프트에서 작물 얘기가 밀린다."""
    긴글 = "○ " + "가" * 200
    나온것 = _첫항목(긴글)
    assert len(나온것) <= 91  # _MAX_LEN + '…'
