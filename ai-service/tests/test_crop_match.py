from app.domain.crop_match import find_crops

# 실제 목록에서 이 검사에 필요한 것만 추렸다. 길이가 규칙을 가르는 기준이라
# 짧은 이름(무·배·배추·수수·옥수수)과 긴 이름(방울토마토·브로콜리)이 둘 다 있어야 한다
아는이름 = [
    "무", "배", "파", "콩", "배추", "수수", "고추", "옥수수", "상추",
    "방울토마토", "브로콜리", "블루베리", "파프리카", "귀리", "사료용 귀리",
    "백합(나리)", "참다래(키위,다래)", "참다래",
]


def test_붙여_쓴_이름을_찾는다():
    assert find_crops("방울토마토에 물을 너무 많이 줬어", 아는이름) == {"방울토마토"}


def test_띄어_쓴_긴_이름도_찾는다():
    # 공백 하나 때문에 작물 필터가 통째로 빠져 벼 물관리 문서가 답으로 나갔다
    assert find_crops("방울 토마토에 물을 너무 많이 줬어", 아는이름) == {"방울토마토"}
    assert find_crops("브로 콜리 삶는 법", 아는이름) == {"브로콜리"}
    assert find_crops("블루 베리 심고싶어", 아는이름) == {"블루베리"}


def test_이름에_원래_공백이_있으면_붙여_써도_찾는다():
    assert "사료용 귀리" in find_crops("사료용귀리 언제 심어?", 아는이름)


def test_짧은_이름에는_공백무시를_걸지_않는다():
    # ⚠ 걸면 '배 추천' 이 '배추' 로, '옥수 수확' 이 '옥수수'·'수수' 로 잡힌다
    assert find_crops("배 추천해줘", 아는이름) == {"배"}
    assert find_crops("옥수 수확 언제해", 아는이름) == set()


def test_공백이_낱말_경계인_경우를_잃지_않는다():
    # '무' 를 잃으면 안 된다 — 공백을 통째로 지우는 방식이 이걸 깨뜨렸다
    assert find_crops("무 배추 심었어", 아는이름) == {"무", "배추"}


def test_낱말_한복판의_한_글자는_작물이_아니다():
    assert find_crops("물을 너무 많이 줬어", 아는이름) == set()
    assert find_crops("재배 방법 알려줘", 아는이름) == set()


def test_괄호_앞_이름도_같이_낸다():
    assert find_crops("참다래 키우기", 아는이름) == {"참다래", "참다래(키위,다래)"}
