-- ─────────────────────────────────────────────────────────────
-- cultivation_events — `했음` 카드마다 메모 한 줄
--
-- `했음` 이 장바구니가 됐다(교안 §6-다, 2026-09-21). 누르면 바로 저장되는 대신
-- 관찰 기록으로 카드가 옮겨가고, 거기서 **카드마다 메모 한 줄**을 적은 뒤 한 번에
-- 저장한다. "물주기 — 호스로 20분" 같은 것이다.
--
-- ⚠️ **`body` 에 몰아넣지 않는다.** `TASK_DONE` 의 `body` 에는 카드 제목이 들어가고,
--    `domain/doneTasks.ts` 의 `hideDoneToday` 가 **그 글자로** 오늘 누른 카드를
--    목록에서 거른다. 제목 뒤에 메모를 붙이면 글자가 달라져 누른 카드가 다시 뜬다.
--
--    `제목\n메모` 로 담고 첫 줄만 보는 길도 있었으나 택하지 않았다 — 글자 안에
--    구조가 숨으면 화면·CSV·거르기가 전부 같은 규칙을 알아야 하고, 나중에 누가
--    `body` 를 그냥 출력하면 제목과 메모가 한 덩어리로 나온다.
--
-- 권한 — 20260917110000 의 grant 가 컬럼이 아니라 테이블 단위라 새 칸도 그대로
-- 덮인다. RLS 정책 넷도 cultivation_id 로만 가르므로 손댈 것이 없다.
-- ─────────────────────────────────────────────────────────────

alter table public.cultivation_events
  -- 그 카드에 대해 사용자가 적은 한 줄. 안 적으면 빈다 — **빈 것이 정상**이다.
  -- 길이 제한은 DB 에 걸지 않는다. 폼이 maxLength 로 막고, 값이 하나 늘 때마다
  -- 마이그레이션을 내야 하는 종류의 칸이 아니다.
  add column if not exists task_note text;
